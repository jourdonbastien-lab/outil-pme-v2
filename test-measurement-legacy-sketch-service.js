'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const Database = require('better-sqlite3');
const { createSketchPngService } = require('./services/sketchPngService');
const { createMeasurementLegacySketchService } = require('./services/measurementLegacySketchService');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'legacy-sketch-'));
const safeResolveInside = (base, ...parts) => {
  const resolvedBase = path.resolve(base), target = path.resolve(resolvedBase, ...parts);
  if (!target.startsWith(resolvedBase + path.sep) && target !== resolvedBase) throw new Error('Chemin invalide');
  return target;
};
const db = new Database(':memory:');
db.exec('CREATE TABLE measurements(id INTEGER PRIMARY KEY); INSERT INTO measurements(id) VALUES(9)');
const png = createSketchPngService({ fs, sketchesDir: root, safeResolveInside, ensureDir: (dir) => fs.mkdirSync(dir, { recursive: true }) });
const service = createMeasurementLegacySketchService({ db, parseOptionalId: (value) => Number(value) > 0 ? Number(value) : null, sketchPngService: png });
assert.strictEqual(service.getMeasurementSketch('bad').error, 'measurement-not-found');
assert.strictEqual(service.getMeasurementSketch(10).error, 'measurement-not-found');
assert.strictEqual(service.getMeasurementSketch(9).error, 'sketch-not-found');
const imageA = 'data:image/png;base64,QUJD';
const saved = service.saveMeasurementSketch(9, imageA);
assert.strictEqual(saved.filePath, path.join(root, 'measurements', '9.png'));
assert.strictEqual(fs.readFileSync(saved.filePath, 'utf8'), 'ABC');
assert.strictEqual(service.getMeasurementSketch(9).filePath, saved.filePath);
service.saveMeasurementSketch(9, 'data:image/png;base64,REVG');
assert.strictEqual(fs.readFileSync(saved.filePath, 'utf8'), 'DEF');
assert.throws(() => service.saveMeasurementSketch(9, 'data:image/jpeg;base64,QUJD'), /Image PNG invalide/);
assert.throws(() => service.saveMeasurementSketch(9, 'data:image/png;base64,'), /Image PNG invalide/);
assert.throws(() => png.save('measurements', 0, imageA), /ID invalide/);
const originalWrite = fs.writeFileSync;
fs.writeFileSync = () => { throw new Error('disque indisponible'); };
assert.throws(() => service.saveMeasurementSketch(9, imageA), /disque indisponible/);
fs.writeFileSync = originalWrite;
db.close();
fs.rmSync(root, { recursive: true, force: true });
console.log('OK - service croquis PNG historique');
