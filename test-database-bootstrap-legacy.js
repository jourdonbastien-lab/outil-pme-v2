'use strict';
const assert = require('assert');
const Database = require('better-sqlite3');
const incomingDocuments = require('./lib/incomingDocuments');
const { bootstrapDatabase } = require('./database/bootstrapDatabase');
const db = new Database(':memory:');
db.exec(`CREATE TABLE users(id INTEGER PRIMARY KEY AUTOINCREMENT,username TEXT UNIQUE,password TEXT); INSERT INTO users(username,password) VALUES('Legacy','test'); CREATE TABLE materials(id INTEGER PRIMARY KEY,name TEXT,type TEXT); INSERT INTO materials(name,type) VALUES('Ancien',NULL); CREATE TABLE tasks(id INTEGER PRIMARY KEY,title TEXT); CREATE TABLE client_orders(id INTEGER PRIMARY KEY,name TEXT NOT NULL,description TEXT,date TEXT NOT NULL,price REAL);`);
bootstrapDatabase(db, { incomingDocuments, logger: { log() {} }, dbPath: ':memory:' });
const names = (table) => db.prepare(`PRAGMA table_info(${table})`).all().map((column) => column.name);
assert(names('users').includes('role'));
assert(names('tasks').includes('to_invoice'));
assert(names('client_orders').includes('quote_id'));
assert(names('client_orders').includes('work_category'));
assert.strictEqual(db.prepare("SELECT type FROM materials WHERE name='Ancien'").get().type, 'tube');
assert.strictEqual(db.prepare("SELECT COUNT(*) AS count FROM users WHERE username='Legacy'").get().count, 1);
assert.strictEqual(db.prepare("SELECT role FROM users WHERE username='Legacy'").get().role, 'admin');
assert.strictEqual(db.prepare("SELECT role FROM users WHERE username='atelier'").get().role, 'atelier');
assert.strictEqual(db.prepare('SELECT COUNT(*) AS count FROM users').get().count, 2);
bootstrapDatabase(db, { incomingDocuments, logger: { log() {} }, dbPath: ':memory:' });
assert.strictEqual(db.prepare('SELECT COUNT(*) AS count FROM users').get().count, 2);
db.close();
console.log('OK - compatibilité base SQLite historique');
