'use strict';
const assert = require('assert');
const Database = require('better-sqlite3');
const { createWorksitesService } = require('./services/worksitesService');
const db = new Database(':memory:');
db.exec(`CREATE TABLE clients (id INTEGER PRIMARY KEY, name TEXT); CREATE TABLE chantiers (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, client_id INTEGER, description TEXT, status TEXT DEFAULT 'À préparer', planned_hours REAL DEFAULT 0, done_hours REAL DEFAULT 0, start_date TEXT, end_date TEXT, created_at TEXT)`);
const statuses = ['À préparer', 'En fabrication', 'En pose', 'En attente', 'Terminé', 'Facturé'];
const normalizeChantierStatus = (value) => statuses.includes(String(value || '').trim()) ? String(value).trim() : 'À préparer';
const parsePositiveNumber = (value) => { const n = Number(value || 0); return Number.isFinite(n) && n > 0 ? n : 0; };
const service = createWorksitesService({ db, normalizeChantierStatus, parsePositiveNumber, now: () => '2026-08-02T10:00:00.000Z' });
assert.deepStrictEqual(service.listWorksites(), { clients: [], worksites: [] });
db.prepare('INSERT INTO clients VALUES (?, ?)').run(1, "Client d'été");
let result = service.createWorksite({ name: 'Atelier', client_id: 99, description: '', status: 'invalide', planned_hours: -2, start_date: '', end_date: '' });
assert.strictEqual(Number(result.lastInsertRowid), 1);
result = service.createWorksite({ name: 'Pose', client_id: 1, description: 'Portail', status: 'En pose', planned_hours: 10, start_date: '2026-08-01', end_date: '2026-08-03' });
assert.strictEqual(Number(result.lastInsertRowid), 2);
let list = service.listWorksites();
assert.strictEqual(list.clients[0].name, "Client d'été");
assert.deepStrictEqual(list.worksites.map((item) => item.id), [2, 1]);
assert.deepStrictEqual([list.worksites[0].plannedHours, list.worksites[0].doneHours, list.worksites[0].progress], [10, 0, 0]);
service.updateWorksite(2, { status: 'Terminé', planned_hours: 8, done_hours: 10, description: '', start_date: '', end_date: '' });
const detail = service.getWorksiteById(2);
assert.deepStrictEqual([detail.normalizedStatus, detail.progress, detail.differenceHours, detail.description], ['Terminé', 100, 2, null]);
assert.strictEqual(service.worksiteProgress(1, 3), 33);
assert.strictEqual(service.worksiteProgress(10, 4), 100);
assert.strictEqual(service.worksiteProgress(3, 0), 0);
assert.strictEqual(service.getWorksiteById(99), undefined);
assert.strictEqual(service.worksiteExists(99), undefined);
db.close();
console.log('OK - service chantiers');
