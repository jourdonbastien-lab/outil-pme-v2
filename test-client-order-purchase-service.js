'use strict';
const assert = require('assert');
const fs = require('fs');
const { createClientOrderPurchaseService } = require('./services/clientOrderPurchaseService');
assert.throws(() => createClientOrderPurchaseService(), /db is required/);
const calls = [];
const db = { prepare(sql) { return { get(...params) { calls.push(['get', sql, params]); return { id: params[0] }; }, run(...params) { calls.push(['run', sql, params]); return { changes: 1 }; } }; } };
const service = createClientOrderPurchaseService({ db });
for (const name of ['getOrder', 'getPurchase', 'createPurchase', 'updatePurchase', 'deletePurchase']) assert.strictEqual(typeof service[name], 'function');
assert.strictEqual(service.getOrder(7).id, 7);
assert.strictEqual(service.getPurchase(3, 7).id, 3);
const purchase = { designation: 'Tube', category: null, qty: 2, unit: 'ml', reference: null, supplier: null, neededDate: null, note: null, status: 'À commander', now: '2026-07-21' };
service.createPurchase(7, purchase); service.updatePurchase(7, 3, purchase); service.deletePurchase(7, 3);
assert(calls.some((call) => call[1].includes('INSERT INTO client_order_purchases')));
assert(calls.some((call) => call[1].includes('UPDATE client_order_purchases')));
assert(calls.some((call) => call[1].includes('DELETE FROM client_order_purchases')));
const source = fs.readFileSync('services/clientOrderPurchaseService.js', 'utf8');
assert(!source.includes('express')); assert(!source.includes("require('../server')"));
console.log('OK - service achats commandes clients');
